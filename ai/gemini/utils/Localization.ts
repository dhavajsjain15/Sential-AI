  public static getDictionary(language: AILocalizationLanguage): LocalizedDictionary {
    return this.dictionaries[language] || this.dictionaries['English'];
  }

  public static getSupportedLanguages(): AILocalizationLanguage[] {
    return Object.keys(this.dictionaries);
  }

  public static translateSystemInstruction(baseInstruction: string, targetLang: AILocalizationLanguage): string {
    if (targetLang === 'English' || !targetLang) return baseInstruction;
    return `${baseInstruction}\n\nIMPORTANT LANGUAGE INSTRUCTION: Provide all headings, summaries, explanations, and instructions in clear ${targetLang}. Use English technical terms in parentheses where appropriate to avoid ambiguity.`;
  }
